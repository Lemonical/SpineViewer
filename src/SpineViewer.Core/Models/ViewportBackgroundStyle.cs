namespace SpineViewer.Core.Models;

/// <summary>
/// Represents the selectable viewport background treatments.
/// </summary>
public enum ViewportBackgroundStyle
{
    /// <summary>
    /// Uses a dark studio background.
    /// </summary>
    Studio = 0,

    /// <summary>
    /// Uses a cooler slate background.
    /// </summary>
    Slate = 1,

    /// <summary>
    /// Uses a blueprint-inspired background.
    /// </summary>
    Blueprint = 2,

    /// <summary>
    /// Uses a light paper-like background.
    /// </summary>
    Paper = 3,
}
