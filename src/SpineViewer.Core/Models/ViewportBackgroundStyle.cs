namespace SpineViewer.Core.Models;

/// <summary>
/// Represents the selectable viewport background treatments.
/// </summary>
public enum ViewportBackgroundStyle
{
    /// <summary>
    /// Uses a black background.
    /// </summary>
    Black = 0,

    /// <summary>
    /// Uses a red background.
    /// </summary>
    Red = 1,

    /// <summary>
    /// Uses a green background.
    /// </summary>
    Green = 2,

    /// <summary>
    /// Uses a light paper-like background.
    /// </summary>
    Paper = 3,

    /// <summary>
    /// Uses a blue background.
    /// </summary>
    Blue = 4,
}
